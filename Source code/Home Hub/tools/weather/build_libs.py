"""Builds the weather page's bundled files so it loads nothing from CDNs:
  weather/icons.js     Lucide icons used by the page (ISC), with a tiny createIcons()
  weather/tailwind.css Tailwind CSS for the classes the page uses (MIT)
Usage: python3 tools/weather/build_libs.py <lucide-icons-dir> <tailwindcss-standalone-binary>
(lucide icons: the lucide-icons-<version>.zip release asset from github.com/lucide-icons/lucide;
 tailwindcss standalone CLI v3: github.com/tailwindlabs/tailwindcss/releases)
Chart.js (weather/chart.umd.js) and SunCalc (weather/suncalc.js) are copied as released."""
import json, os, re, subprocess, sys, tempfile

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
PAGE = os.path.join(ROOT, "weather", "index.html")

def icons(icon_dir):
    page = open(PAGE, encoding="utf-8").read()
    names = sorted(n for n in set(re.findall(r"['\"`= ]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['\"`]", page))
                   if os.path.exists(os.path.join(icon_dir, n + ".svg")))
    m = {}
    for n in names:
        svg = open(os.path.join(icon_dir, n + ".svg"), encoding="utf-8").read()
        svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
        m[n] = re.sub(r"\s+", " ", svg).strip()
    js = ("// Lucide icons (ISC License, https://lucide.dev) used by Your Weather. Generated by tools/weather/build_libs.py.\n"
          "(function(){var I=" + json.dumps(m, separators=(",", ":")) + ";\n"
          "window.lucide={icons:I,createIcons:function(){document.querySelectorAll('i[data-lucide]').forEach(function(i){"
          "var s=I[i.getAttribute('data-lucide')];if(!s)return;var t=document.createElement('template');t.innerHTML=s;var el=t.content.firstElementChild;"
          "for(var k=0;k<i.attributes.length;k++){var a=i.attributes[k];if(a.name!=='class'&&a.name!=='data-lucide')el.setAttribute(a.name,a.value);}"
          "el.setAttribute('data-lucide',i.getAttribute('data-lucide'));el.setAttribute('class','lucide lucide-'+i.getAttribute('data-lucide')+' '+(i.getAttribute('class')||''));"
          "i.replaceWith(el);});}};})();\n")
    open(os.path.join(ROOT, "weather", "icons.js"), "w", encoding="utf-8").write(js)
    print(len(names), "icons")

def tailwind(cli):
    cfg = ("module.exports = { content: [%s], theme: { extend: { fontFamily: { sans: ['Inter', 'sans-serif'], mono: ['JetBrains Mono', 'monospace'] },"
           " colors: { midnight: '#020617', surface: '#0f172a' } } } };") % json.dumps(PAGE)
    with tempfile.TemporaryDirectory() as d:
        c, i = os.path.join(d, "tw.config.js"), os.path.join(d, "in.css")
        open(c, "w").write(cfg)
        open(i, "w").write("@tailwind base;\n@tailwind components;\n@tailwind utilities;\n")
        subprocess.check_call([cli, "-c", c, "-i", i, "-o", os.path.join(ROOT, "weather", "tailwind.css"), "--minify"])

if __name__ == "__main__":
    icons(sys.argv[1])
    tailwind(sys.argv[2])
